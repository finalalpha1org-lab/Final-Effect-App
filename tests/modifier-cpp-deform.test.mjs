import assert from 'node:assert/strict';
import test from 'node:test';
import { readFileSync } from 'node:fs';
import * as THREE from 'three';
import { appPath } from './app-paths.mjs';
import {
  armatureSkinGeometry, bindSurfaceDeform, createLatticeCageGeometry,
  latticeDeformGeometry, shrinkwrapGeometry, surfaceDeformGeometry
} from '../src/modifier-geometry.mjs';

/* =========================================================================
 * These cases install the real compiled core as globalThis.FECppEngine, so the
 * deformation bridge takes the C++ path. They also re-run the same input on the
 * JS reference path and require bit-for-bit agreement, which proves the session
 * marshalling, the FFD/DQ/shrinkwrap/surface-deform kernels and the returned
 * buffers.
 * ========================================================================= */

const wasmBytes = readFileSync(appPath('fe_core_engine.wasm'));
const instance = new WebAssembly.Instance(new WebAssembly.Module(wasmBytes), {});
const exports = instance.exports;

function withCore(run) {
  const previous = globalThis.FECppEngine;
  globalThis.FECppEngine = { exports, memory: exports.memory, ready: true };
  try {
    return run();
  } finally {
    if (previous === undefined) delete globalThis.FECppEngine;
    else globalThis.FECppEngine = previous;
  }
}

function withoutCore(run) {
  const previous = globalThis.FECppEngine;
  delete globalThis.FECppEngine;
  try {
    return run();
  } finally {
    if (previous !== undefined) globalThis.FECppEngine = previous;
  }
}

function positions(geometry) {
  return Float32Array.from(geometry.attributes.position.array);
}

function finite(geometry) {
  const p = geometry.attributes.position;
  for (let i = 0; i < p.count * 3; i++) if (!Number.isFinite(p.array[i])) return false;
  return true;
}

function boundingBox(geometry) {
  geometry.computeBoundingBox();
  return geometry.boundingBox;
}

function maxDelta(a, b) {
  const pa = a.attributes.position.array, pb = b.attributes.position.array;
  assert.equal(pa.length, pb.length);
  let delta = 0;
  for (let i = 0; i < pa.length; i++) delta = Math.max(delta, Math.abs(pa[i] - pb[i]));
  return delta;
}

function widenedCage(geometry, divisions = [2, 2, 2]) {
  const cage = createLatticeCageGeometry(geometry, divisions, 0.05);
  const pos = cage.attributes.position;
  for (let i = 0; i < pos.count; i++) {
    if (pos.getY(i) > 0.4) pos.setXYZ(i, pos.getX(i) * 1.65, pos.getY(i), pos.getZ(i) * 1.65);
  }
  return cage;
}

test('C++ FFD lattice cage is generated by the core and deforms the mesh', () => {
  const cylinder = new THREE.CylinderGeometry(0.6, 0.6, 2.0, 16, 8);
  const jsCage = withoutCore(() => widenedCage(cylinder));
  const cppCage = withCore(() => widenedCage(cylinder));

  /* 3x3x3 control points for a 2x2x2 FFD cage, six triangulated outer faces. */
  assert.equal(cppCage.attributes.position.count, 27);
  assert.equal(cppCage.userData.restPositions.length, 27 * 3);
  assert.deepEqual(cppCage.userData.divisions, [2, 2, 2]);
  assert.ok(cppCage.userData.boundsMin.every(Number.isFinite));
  assert.ok(cppCage.userData.boundsMax.every(Number.isFinite));
  assert.ok(maxDelta(cppCage, jsCage) < 1e-5, 'C++ cage matches the JS reference cage');

  const cppFfd = withCore(() => latticeDeformGeometry(cylinder, cppCage.userData.restPositions,
    cppCage.attributes.position.array, cppCage.userData.divisions, new THREE.Matrix4().elements, 1));
  const jsFfd = withoutCore(() => latticeDeformGeometry(cylinder, jsCage.userData.restPositions,
    jsCage.attributes.position.array, jsCage.userData.divisions, new THREE.Matrix4().elements, 1));

  assert.ok(finite(cppFfd));
  assert.ok(maxDelta(cppFfd, jsFfd) < 1e-5, 'C++ Bernstein FFD matches the JS reference');
  assert.ok(boundingBox(cppFfd).max.x > boundingBox(cylinder).max.x * 1.25, 'lattice widens the top of the cylinder');
});

test('C++ armature skinning runs the dual-quaternion and LBS paths', () => {
  const mesh = () => new THREE.CylinderGeometry(0.35, 0.35, 2.4, 16, 16);
  const options = { influence: 1, preserveVolume: true, bendDeg: 45, twistDeg: 25 };
  const cppDqs = withCore(() => armatureSkinGeometry(mesh(), options));
  const jsDqs = withoutCore(() => armatureSkinGeometry(mesh(), options));
  const cppLbs = withCore(() => armatureSkinGeometry(mesh(), { ...options, preserveVolume: false }));
  const jsLbs = withoutCore(() => armatureSkinGeometry(mesh(), { ...options, preserveVolume: false }));

  assert.ok(finite(cppDqs) && finite(cppLbs));
  assert.ok(maxDelta(cppDqs, jsDqs) < 1e-5, 'C++ dual-quaternion skinning matches the JS reference');
  assert.ok(maxDelta(cppLbs, jsLbs) < 1e-5, 'C++ linear-blend skinning matches the JS reference');
  assert.ok(boundingBox(cppDqs).min.x < -0.45 || boundingBox(cppDqs).max.x > 0.45, 'bent bone moves the mesh');
  assert.ok(maxDelta(cppDqs, cppLbs) > 1e-4, 'Preserve Volume changes the result instead of being ignored');
});

test('C++ shrinkwrap projects onto the transformed target in every mode', () => {
  const source = () => new THREE.SphereGeometry(0.25, 8, 6);
  const target = new THREE.PlaneGeometry(4, 4);
  const matrix = new THREE.Matrix4().makeTranslation(0, 0, 1).elements;
  const jsWrap = withoutCore(() => shrinkwrapGeometry(source(), target, matrix, 0, 'On Surface'));
  const cppWrap = withCore(() => shrinkwrapGeometry(source(), target, matrix, 0, 'On Surface'));

  assert.ok(finite(cppWrap));
  assert.ok(maxDelta(cppWrap, jsWrap) < 1e-5, 'C++ nearest-surface projection matches the JS reference');
  assert.ok(Math.abs(boundingBox(cppWrap).min.z - 1) < 1e-5);
  assert.ok(Math.abs(boundingBox(cppWrap).max.z - 1) < 1e-5);

  const cloth = () => {
    const sheet = new THREE.PlaneGeometry(1.5, 1.5, 16, 16);
    sheet.rotateX(-Math.PI / 2);
    sheet.translate(0, 1.8, 0);
    return sheet;
  };
  const sphere = new THREE.SphereGeometry(1.0, 32, 24);
  const identity = new THREE.Matrix4().elements;
  const above = withCore(() => shrinkwrapGeometry(cloth(), sphere, identity, 0.08, 'Above Surface'));
  for (let i = 0; i < above.attributes.position.count; i++) {
    const p = above.attributes.position;
    const radius = Math.hypot(p.getX(i), p.getY(i), p.getZ(i));
    assert.ok(radius >= 1.04, `Above Surface keeps vertices outside the sphere (got ${radius})`);
  }

  /* Outside Surface flips the projection normal when the source sits behind the
   * target face, so a negative offset pushes through instead of backing off. */
  const below = () => {
    const blob = new THREE.SphereGeometry(0.25, 8, 6);
    blob.translate(0, 0, -0.5);
    return blob;
  };
  const floor = () => new THREE.PlaneGeometry(4, 4);
  const outside = withCore(() => shrinkwrapGeometry(below(), floor(), identity, 0.05, 'Outside Surface'));
  const outsideJs = withoutCore(() => shrinkwrapGeometry(below(), floor(), identity, 0.05, 'Outside Surface'));
  const onSurface = withCore(() => shrinkwrapGeometry(below(), floor(), identity, 0.05, 'On Surface'));
  assert.ok(maxDelta(outside, outsideJs) < 1e-5, 'C++ Outside Surface matches the JS reference');
  assert.ok(Math.abs(boundingBox(outside).max.z + 0.05) < 1e-5, 'Outside Surface pushes away along the flipped normal');
  assert.ok(Math.abs(boundingBox(onSurface).max.z - 0.05) < 1e-5, 'On Surface offset follows the face normal');
});

test('C++ surface deform bind + apply tracks a moving target surface', () => {
  const badge = () => {
    const geometry = new THREE.BoxGeometry(0.5, 0.1, 0.5, 4, 2, 4);
    geometry.translate(0, 0.08, 0);
    return geometry;
  };
  const driver = () => {
    const geometry = new THREE.PlaneGeometry(2, 2, 8, 8);
    geometry.rotateX(-Math.PI / 2);
    return geometry;
  };
  const moved = () => {
    const geometry = driver();
    geometry.translate(0, 0.75, 0);
    return geometry;
  };
  const identity = new THREE.Matrix4().elements;

  const jsBinding = withoutCore(() => bindSurfaceDeform(badge(), driver(), identity));
  const cppBinding = withCore(() => bindSurfaceDeform(badge(), driver(), identity));

  assert.equal(cppBinding.vertexTri.length, badge().attributes.position.count);
  assert.equal(cppBinding.triIndices.length, jsBinding.triIndices.length);
  assert.equal(cppBinding.targetVertexCount, driver().attributes.position.count);
  assert.deepEqual(Array.from(cppBinding.vertexTri), Array.from(jsBinding.vertexTri), 'C++ picks the same triangles');
  for (let i = 0; i < jsBinding.bary.length; i++) {
    assert.ok(Math.abs(cppBinding.bary[i] - jsBinding.bary[i]) < 1e-5, 'C++ barycentric weights match');
  }

  const cppDeformed = withCore(() => surfaceDeformGeometry(badge(), cppBinding, moved(), identity, 1));
  const jsDeformed = withoutCore(() => surfaceDeformGeometry(badge(), jsBinding, moved(), identity, 1));
  assert.ok(finite(cppDeformed));
  assert.ok(maxDelta(cppDeformed, jsDeformed) < 1e-5, 'C++ surface deform matches the JS reference');
  assert.ok(boundingBox(cppDeformed).min.y > 0.65, 'deformed badge follows the lifted driver');
});
