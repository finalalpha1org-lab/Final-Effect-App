import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { appPath } from './app-paths.mjs';

/* Every grass blade in the studio was vertex colour and nothing else: a flat
   strip lit by one normal, which is why a close-up of the ground read as
   painted slats while the trees had bark. A blade is not a slat: it folds away
   from its midrib, it carries parallel veins, and its tip dries out. The maps
   below are what put that on screen, and they are generated by a pure function
   so they can be measured instead of eyed. */

const html = readFileSync(appPath('Terrain_system_.html'), 'utf8');
const models = readFileSync('terrain-main-02.js', 'utf8');
const lod = readFileSync('terrain-main-03.js', 'utf8');

function blade() {
  const source = html.slice(html.indexOf('function bladePixels('), html.indexOf('const BLADE='));
  assert.ok(source.length > 200, 'the blade generator must be in the shipped page');
  return new Function(`${source}; return bladePixels;`)();
}

const W = 128, H = 256;

test('the blade albedo modulates the vertex colour near white, and does not mute it', () => {
  /* The old blade atlas painted the grass its own green and the vertex colours —
     the ones the whole palette is tuned around — were multiplied into darkness.
     A modulation map has to stay near white; the plant's colour belongs to the
     vertex buffer. */
  const px = blade().call(null, W, H, 0x9e3779b9);
  const lum = (i) => (0.2126 * px.albedo[i] + 0.7152 * px.albedo[i + 1] + 0.0722 * px.albedo[i + 2]) / 255;
  let sum = 0, min = 1, max = 0;
  for (let j = 0; j < H; j++) {
    for (let i = 0; i < W; i++) {
      const k = (j * W + i) * 4;
      const value = lum(k);
      assert.ok(Number.isFinite(value), 'albedo must be finite everywhere');
      sum += value; min = Math.min(min, value); max = Math.max(max, value);
      assert.equal(px.albedo[k + 3], 255, 'the albedo has to be opaque');
    }
  }
  const mean = sum / (W * H);
  assert.ok(mean > 0.90 && mean < 0.98, `the modulation must stay near white (mean ${mean.toFixed(3)})`);
  assert.ok(max - min > 0.02, `it still has to carry structure (range ${(max - min).toFixed(3)})`);
  assert.ok(max - min < 0.2, `...without becoming a painted stripe (range ${(max - min).toFixed(3)})`);

  /* Veins: a periodic structure across the blade, four a side. */
  const row = 128 * W + 0;
  const across = [];
  for (let i = 0; i < W; i++) across.push(lum((row + i) * 4));
  const middle = across.slice(Math.floor(W * 0.2), Math.floor(W * 0.8));
  assert.ok(Math.max(...middle) - Math.min(...middle) > 0.01, 'the veins have to be visible across the blade');

  /* The tip dries warmer than the base — that is what late-season grass does. */
  const warmth = (row) => {
    let total = 0;
    for (let i = 0; i < W; i++) {
      const k = (row * W + i) * 4;
      total += px.albedo[k] - px.albedo[k + 2];
    }
    return total / W;
  };
  assert.ok(warmth(H - 4) > warmth(8) + 4, 'the tip must dry warmer than the base');
});

test('the blade normal map is a fold, not noise', () => {
  const px = blade()(W, H, 0x9e3779b9);
  const nx = (k) => (px.normal[k] / 255) * 2 - 1;
  const ny = (k) => (px.normal[k + 1] / 255) * 2 - 1;
  const nz = (k) => (px.normal[k + 2] / 255) * 2 - 1;
  let left = 1, right = -1, unit = true;
  for (let j = 0; j < H; j++) {
    for (let i = 0; i < W; i++) {
      const k = (j * W + i) * 4;
      const length = Math.hypot(nx(k), ny(k), nz(k));
      if (Math.abs(length - 1) > 0.02) unit = false;
      /* The map has to be brighter than mid-blue down the middle, or three
         reads it as an inverted normal. */
      assert.ok(nz(k) > 0, 'a normal map must point out of the surface');
      if (i < W * 0.1) left = Math.min(left, nx(k));
      if (i > W * 0.9) right = Math.max(right, nx(k));
    }
  }
  assert.ok(unit, 'every normal must be unit length');
  assert.ok(left < -0.3, `the blade must fold away on one side (nx ${left.toFixed(2)})`);
  assert.ok(right > 0.3, `...and the other (nx ${right.toFixed(2)})`);
});

test('the generator is deterministic and independent of the global seed stream', () => {
  const bladeFn = blade();
  const first = bladeFn(W, H, 12345).albedo;
  const second = bladeFn(W, H, 12345).albedo;
  assert.deepEqual(Array.from(first), Array.from(second), 'the same seed must paint the same blade');
  const other = bladeFn(W, H, 999).albedo;
  assert.notDeepEqual(Array.from(first), Array.from(other), 'a different seed paints a different blade');
  /* It must not consume the studio's shared RNG: that would shift every texture
     and every tree drawn after it. */
  const source = html.slice(html.indexOf('function bladePixels('), html.indexOf('const BLADE='));
  assert.equal(/\bR\(\)/.test(source), false, 'the blade must not draw from the global random stream');
});

test('grass UVs run from the soil to the tip instead of restarting on every quad', () => {
  /* The quad default was [[0,0],[1,0],[1,1],[0,1]] for every segment, so a
     blade texture would tile three or four times along one leaf. */
  for (const name of ['grassG', 'tallGrassG']) {
    const start = models.indexOf(`const ${name}=`);
    const block = models.slice(start, models.indexOf('gaGeo(g)})();', start));
    assert.match(block, /\[\[0,t0\],\[1,t0\],\[1,t1\],\[0,t1\]\]/,
      `${name} must lay its UVs along the blade (u across, v base to tip)`);
  }
  /* ...and the blades actually get the maps. */
  assert.match(models, /mk\('grass',105000,\[\[grassG,\{std:1,ds:1,w:\.11,fx:'gl',tk:25,map:BLADE\.albedo,nm:BLADE\.normal,ns:\.55/,
    'lawn grass carries the blade albedo and its fold normal');
  assert.match(models, /mk\('tallgrass',80000,\[\[tallGrassG,\{std:1,ds:1,w:\.14,fx:'gl',tk:22,map:BLADE\.albedo,nm:BLADE\.normal,ns:\.55/,
    'tall grass carries them too');
  assert.match(models, /const BLADE=\(\(\)=>\{[\s\S]{0,600}?albedo:mkTex\(ca\),normal:mkTex\(cn,false\)\}/,
    'the albedo is colour and the normal is data — no sRGB decode on the fold map');
  /* The far tier drops the maps, which is what keeps a 105k-instance draw cheap. */
  assert.match(lod, /lowMat\.normalMap=null;lowMat\.roughnessMap=null;lowMat\.bumpMap=null;/,
    'the low-detail twin must drop the normal map');
  assert.equal(/lowMat\.map=null/.test(lod), false,
    'the far tier keeps the albedo (one fetch, and it is the colour) and drops only the relief maps');
});
